/** Atlas name -> name to show. */
export const DISPLAY_NAME: Record<string, string> = Object.fromEntries(
  Object.entries(COUNTRIES).map(([atlas, [display]]) => [atlas, display]),
);

export const displayName = (atlasName: string) => DISPLAY_NAME[atlasName] ?? atlasName;

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Case-sensitive on purpose: "Chad", "Jordan", "US" are names only when capitalised.
const MATCHERS: [string, RegExp][] = Object.entries(COUNTRIES).map(([atlas, [, ...words]]) => [
  atlas,
  new RegExp(`(?<![\\p{L}\\p{N}])(?:${words.map(escape).join('|')})(?![\\p{L}\\p{N}])`, 'u'),
]);

/** Phrases that contain another country's name; taken out before that country is looked for. */
const CONTAINS: Record<string, RegExp> = {
  Sudan: /South Sudan(?:ese)?/g,
  Guinea: /(?:Papua New|Equatorial) Guinea/g,
  Congo: /Democratic Republic of (?:the )?Congo|DR Congo/g,
  'South Korea': /Democratic People's Republic of Korea/g,
};

/** The countries (atlas names) a headline names, each once. */
export function mentionedCountries(title: string): string[] {
  const found: string[] = [];
  for (const [atlas, matcher] of MATCHERS) {
    const text = CONTAINS[atlas] ? title.replace(CONTAINS[atlas], ' ') : title;
    if (matcher.test(text)) found.push(atlas);
  }
  return found;
}
